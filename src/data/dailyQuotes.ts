export function getTodayQuote(): string {
  const today = new Date();
  // 日付をシード値として使用（年月日で固定）
  const seed = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  const index = seed % dailyQuotes.length;
  return dailyQuotes[index];
}

